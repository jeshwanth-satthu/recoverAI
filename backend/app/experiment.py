from collections import defaultdict
from uuid import uuid4

from app.database import transactions_collection

from app.baseline import baseline_recovery

from app.engine import recover_transaction

from app.repositories.experiment_repository import (
    create_experiment
)


def run_experiment():
    """
    Run a reproducible comparison between:

    1. Baseline recovery strategy
    2. RecoverAI recovery pipeline

    The experiment only evaluates synthetic transactions
    generated by transaction_generator.py.
    """

    # =========================================================
    # 1. LOAD ELIGIBLE SYNTHETIC TRANSACTIONS
    # =========================================================

    transactions = list(
        transactions_collection.find(
            {
                "id": {
                    "$regex": "^txn_"
                },
                "recoverable": True
            },
            {
                "_id": 0
            }
        )
    )

    if not transactions:
        return {
            "success": False,
            "error": (
                "No synthetic recoverable "
                "transactions found"
            )
        }

    # =========================================================
    # 2. BASELINE
    # =========================================================

    baseline_results = []

    for transaction in transactions:

        result = baseline_recovery(
            transaction
        )

        baseline_results.append(result)

    baseline_recovered = sum(
        result.get(
            "amount_recovered",
            0
        )
        for result in baseline_results
    )

    baseline_successful_cases = sum(
        1
        for result in baseline_results
        if result.get("recovered") is True
    )

    # =========================================================
    # 3. RECOVERAI
    # =========================================================

    recoverai_results = []

    for transaction in transactions:

        result = recover_transaction(
            transaction["id"]
        )

        verification = result.get(
            "verification",
            {}
        )

        recoverai_results.append(
            {
                "transaction_id": transaction["id"],
                "recovered": verification.get(
                    "recovered",
                    False
                ),
                "amount_recovered": verification.get(
                    "amount_recovered",
                    0
                ),
                "status": verification.get(
                    "status",
                    result.get(
                        "status",
                        "unknown"
                    )
                ),
                "guardrail_passed": result.get(
                    "guardrail",
                    {}
                ).get(
                    "passed",
                    False
                ),
                "human_approval": result.get(
                    "guardrail",
                    {}
                ).get(
                    "requires_human_approval",
                    False
                )
            }
        )

    # =========================================================
    # 4. RECOVERAI TOTALS
    # =========================================================

    recoverai_recovered = sum(
        result.get(
            "amount_recovered",
            0
        )
        for result in recoverai_results
    )

    recoverai_successful_cases = sum(
        1
        for result in recoverai_results
        if result.get("recovered") is True
    )

    recoverai_pending_cases = sum(
        1
        for result in recoverai_results
        if result.get("status") == "pending"
    )

    recoverai_stopped_cases = sum(
        1
        for result in recoverai_results
        if result.get("status") == "stopped"
    )

    recoverai_human_approval_cases = sum(
        1
        for result in recoverai_results
        if result.get("human_approval") is True
    )

    # =========================================================
    # 5. REVENUE AT RISK
    # =========================================================

    revenue_at_risk = sum(
        transaction["amount"]
        for transaction in transactions
    )

    # =========================================================
    # 6. RECOVERY RATES
    # =========================================================

    baseline_recovery_rate = (
        (
            baseline_recovered
            / revenue_at_risk
        ) * 100
        if revenue_at_risk > 0
        else 0
    )

    recoverai_recovery_rate = (
        (
            recoverai_recovered
            / revenue_at_risk
        ) * 100
        if revenue_at_risk > 0
        else 0
    )

    # =========================================================
    # 7. CASE RECOVERY RATES
    # =========================================================

    total_cases = len(transactions)

    baseline_case_recovery_rate = (
        (
            baseline_successful_cases
            / total_cases
        ) * 100
        if total_cases > 0
        else 0
    )

    recoverai_case_recovery_rate = (
        (
            recoverai_successful_cases
            / total_cases
        ) * 100
        if total_cases > 0
        else 0
    )

    # =========================================================
    # 8. INCREMENTAL RECOVERY
    # =========================================================

    incremental_recovery = (
        recoverai_recovered
        - baseline_recovered
    )

    improvement_percent = (
        (
            incremental_recovery
            / baseline_recovered
        ) * 100
        if baseline_recovered > 0
        else 0
    )

    # =========================================================
    # 9. FAILURE-REASON ANALYSIS
    # =========================================================

    reason_analysis = defaultdict(
        lambda: {
            "cases": 0,
            "revenue_at_risk": 0,
            "baseline_recovered": 0,
            "recoverai_recovered": 0,
            "baseline_successes": 0,
            "recoverai_successes": 0,
            "guardrail_blocked": 0,
            "pending": 0,
            "human_approval": 0,
            "stopped": 0
        }
    )

    # ---------------------------------------------------------
    # Populate transaction-level information
    # ---------------------------------------------------------

    transaction_map = {
        transaction["id"]: transaction
        for transaction in transactions
    }

    for transaction in transactions:

        reason = (
            transaction.get(
                "failure_reason"
            )
            or transaction.get(
                "status"
            )
            or "unknown"
        )

        reason_analysis[reason][
            "cases"
        ] += 1

        reason_analysis[reason][
            "revenue_at_risk"
        ] += transaction.get(
            "amount",
            0
        )

    # ---------------------------------------------------------
    # Baseline analysis
    # ---------------------------------------------------------

    for index, transaction in enumerate(
        transactions
    ):

        reason = (
            transaction.get(
                "failure_reason"
            )
            or transaction.get(
                "status"
            )
            or "unknown"
        )

        result = baseline_results[index]

        amount_recovered = result.get(
            "amount_recovered",
            0
        )

        reason_analysis[reason][
            "baseline_recovered"
        ] += amount_recovered

        if result.get(
            "recovered"
        ) is True:

            reason_analysis[reason][
                "baseline_successes"
            ] += 1

    # ---------------------------------------------------------
    # RecoverAI analysis
    # ---------------------------------------------------------

    for result in recoverai_results:

        transaction = transaction_map.get(
            result["transaction_id"]
        )

        if not transaction:
            continue

        reason = (
            transaction.get(
                "failure_reason"
            )
            or transaction.get(
                "status"
            )
            or "unknown"
        )

        reason_analysis[reason][
            "recoverai_recovered"
        ] += result.get(
            "amount_recovered",
            0
        )

        if result.get(
            "recovered"
        ) is True:

            reason_analysis[reason][
                "recoverai_successes"
            ] += 1

        if (
            result.get(
                "guardrail_passed"
            ) is False
        ):

            reason_analysis[reason][
                "guardrail_blocked"
            ] += 1

        if result.get(
            "status"
        ) == "pending":

            reason_analysis[reason][
                "pending"
            ] += 1

        if result.get(
            "human_approval"
        ) is True:

            reason_analysis[reason][
                "human_approval"
            ] += 1

        if result.get(
            "status"
        ) == "stopped":

            reason_analysis[reason][
                "stopped"
            ] += 1

    # Convert defaultdict → normal dict
    reason_analysis = dict(
        reason_analysis
    )

    # =========================================================
    # 10. CALCULATE REASON-LEVEL RATES
    # =========================================================

    for reason, data in reason_analysis.items():

        risk = data[
            "revenue_at_risk"
        ]

        if risk > 0:

            data[
                "baseline_recovery_rate_percent"
            ] = round(
                (
                    data[
                        "baseline_recovered"
                    ]
                    / risk
                ) * 100,
                2
            )

            data[
                "recoverai_recovery_rate_percent"
            ] = round(
                (
                    data[
                        "recoverai_recovered"
                    ]
                    / risk
                ) * 100,
                2
            )

        else:

            data[
                "baseline_recovery_rate_percent"
            ] = 0

            data[
                "recoverai_recovery_rate_percent"
            ] = 0

    # =========================================================
    # 11. EXPERIMENT DOCUMENT
    # =========================================================

    experiment = {
        "experiment_id": (
            f"EXP-{uuid4().hex[:8].upper()}"
        ),

        "dataset": "synthetic_txn_v1",

        "transaction_count": total_cases,

        "revenue_at_risk": revenue_at_risk,

        # -----------------------------------------------------
        # Baseline
        # -----------------------------------------------------

        "baseline": {
            "revenue_recovered": (
                baseline_recovered
            ),

            "recovery_rate_percent": round(
                baseline_recovery_rate,
                2
            ),

            "successful_cases": (
                baseline_successful_cases
            ),

            "case_recovery_rate_percent": round(
                baseline_case_recovery_rate,
                2
            )
        },

        # -----------------------------------------------------
        # RecoverAI
        # -----------------------------------------------------

        "recoverai": {
            "revenue_recovered": (
                recoverai_recovered
            ),

            "recovery_rate_percent": round(
                recoverai_recovery_rate,
                2
            ),

            "successful_cases": (
                recoverai_successful_cases
            ),

            "case_recovery_rate_percent": round(
                recoverai_case_recovery_rate,
                2
            ),

            "pending_cases": (
                recoverai_pending_cases
            ),

            "stopped_cases": (
                recoverai_stopped_cases
            ),

            "human_approval_cases": (
                recoverai_human_approval_cases
            )
        },

        # -----------------------------------------------------
        # Comparison
        # -----------------------------------------------------

        "incremental_recovery": (
            incremental_recovery
        ),

        "improvement_percent": round(
            improvement_percent,
            2
        ),

        # -----------------------------------------------------
        # Detailed analysis
        # -----------------------------------------------------

        "reason_analysis": reason_analysis
    }

    # =========================================================
    # 12. SAVE EXPERIMENT
    # =========================================================

    create_experiment(
        experiment
    )

    # =========================================================
    # 13. RETURN RESULT
    # =========================================================

    return {
        "success": True,
        **experiment
    }